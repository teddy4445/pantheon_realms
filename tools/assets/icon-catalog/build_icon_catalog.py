#!/usr/bin/env python3
"""
Icon catalog — document step (development tool; never packaged in the game).

Reads assets-source/icons/icon-inventory.json (written by the inventory step)
and writes:

  ICON_CATALOG.md                      the central, readable catalog (repo root)
  assets-source/icons/icon_catalog.csv one row per icon (for any tool)
  assets-source/icons/ICON_CATALOG.xlsx one sheet per section, with thumbnails
                                        of what the game shows today and a
                                        Status column to track production

Needs: openpyxl, Pillow.  Run through `npm run icons:catalog`.
"""
import csv
import json
import os
import sys
import tempfile
from datetime import date

from openpyxl import Workbook
from openpyxl.drawing.image import Image as XLImage
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter
from openpyxl.worksheet.datavalidation import DataValidation
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
SRC = os.path.join(ROOT, 'assets-source', 'icons')
THUMBS = os.path.join(tempfile.gettempdir(), 'pantheon-realms-icon-thumbs')

with open(os.path.join(SRC, 'icon-inventory.json'), encoding='utf-8') as f:
    INV = json.load(f)

CURRENT_LABEL = {
    'art': 'Art',
    'glyph': 'SVG glyph',
    'fallback': 'Stand-in (effect family)',
    'procedural': 'Generated placeholder / text',
}


def current_file(cur):
    """Repo-relative image of what the game shows today (None for procedural)."""
    if cur['type'] == 'glyph':
        return cur['file'].replace('.svg', '.png')
    return cur.get('file')


def current_text(cur):
    label = CURRENT_LABEL[cur['type']]
    if cur['type'] == 'art':
        label = 'Final art' if cur.get('status') == 'final' else 'Placeholder art'
    extra = cur.get('note') or cur.get('file') or ''
    if cur['type'] == 'glyph':
        extra = f"glyph '{cur['glyph']}'"
    return f'{label} — {extra}' if extra else label


def md_escape(s):
    return (s or '').replace('|', '\\|').replace('\n', ' ')


# ---------------------------------------------------------------------------
# Markdown
# ---------------------------------------------------------------------------

def build_markdown():
    style = INV['style']
    sections = INV['sections']
    total = sum(len(s['rows']) for s in sections)
    now = sum(1 for s in sections for r in s['rows'] if r['priority'] == 'now')
    out = []
    out.append('# Icon catalog — every icon and small illustration in Pantheon Realms\n')
    out.append(
        f'Generated by `npm run icons:catalog` from the game itself (content `{INV["contentVersion"]}`, {date.today().isoformat()}). '
        'Do not edit by hand: change the content or `tools/assets/icon-catalog/briefs.ts` and run it again. '
        f'**{total} entries** in {len(sections)} sections; **{now}** have no art of their own yet (only a glyph, a stand-in or a generated placeholder) and are marked *now*. '
        'The same list, with thumbnails of what the game shows today and a Status column for production, is in '
        '[`assets-source/icons/ICON_CATALOG.xlsx`](assets-source/icons/ICON_CATALOG.xlsx) '
        '(and [`icon_catalog.csv`](assets-source/icons/icon_catalog.csv)).\n'
    )
    out.append('## How to deliver an icon\n')
    out.append(
        '1. Draw it to the size in its section (larger masters are welcome; keep a copy in `assets-source/icons/masters/`).\n'
        '2. Name the PNG exactly as its **asset ID** plus `.png` (for example `icon.spell.rune_of_tyr.png`).\n'
        '3. Put it in `assets-source/icons/final/` and run `npm run icons:import`: it is checked against this catalog, sized for the game, '
        'copied to `assets-runtime/ui/icons/final/` and registered in `assets-runtime/ui/final-manifest.json`. '
        'The game shows it in place of the stand-in by asset ID — no screen changes (ASSET_PIPELINE.md §11).\n'
        '4. Run `npm run icons:catalog` again: the entry shows the new art and leaves the *now* list.\n'
        '\nInterface icons that have only a glyph today (asset IDs `icon.ui.<name>`) and spells, artifacts, skills, portraits and emblems are picked up the same way. '
        'Two groups are reserved for later screens and are not drawn yet even when delivered: artifact-set emblems (`icon.set.*`) and creature-ability badges (`icon.ability.*`).\n'
    )
    out.append('## Style guide\n')
    for k, v in style.items():
        out.append(f'* **{k.capitalize()}:** {v}')
    out.append('')
    out.append('## Contents\n')
    out.append('| Section | Entries | Without art yet (*now*) | Size |')
    out.append('|---|---:|---:|---|')
    for s in sections:
        n_now = sum(1 for r in s['rows'] if r['priority'] == 'now')
        out.append(f"| [{s['title']}](#{s['id']}) | {len(s['rows'])} | {n_now} | {s['size']} |")
    out.append('')
    for s in sections:
        out.append(f'<a id="{s["id"]}"></a>\n')
        out.append(f'## {s["title"]}\n')
        out.append(f'{s["intro"]} **Size:** {s["size"]}.\n')
        has_pantheon = any(r.get('pantheon') for r in s['rows'])
        head = '| Now | Asset ID (deliver as) | Name | ' + ('Pantheon | ' if has_pantheon else '') + 'Shown on | Today | What to draw |'
        out.append(head)
        out.append('|---|---|---|' + ('---|' if has_pantheon else '') + '---|---|---|')
        for r in s['rows']:
            img = current_file(r['current'])
            thumb = f'<img src="{img}" width="28" alt="">' if img and os.path.exists(os.path.join(ROOT, img)) else '—'
            brief = md_escape(r['brief'])
            if r.get('details'):
                brief += f"<br><sub>{md_escape(r['details'])}</sub>"
            cells = [
                thumb,
                f"`{r['assetId']}`",
                md_escape(r['name']) + (f"<br><sub>{md_escape(r['group'])}</sub>" if r.get('group') else ''),
            ]
            if has_pantheon:
                cells.append(md_escape(r.get('pantheon') or ''))
            cells += [md_escape(r['where']), md_escape(current_text(r['current'])) + (' · **now**' if r['priority'] == 'now' else ''), brief]
            out.append('| ' + ' | '.join(cells) + ' |')
        out.append('')
    if INV.get('unusedIconFiles'):
        out.append('## Delivered icon art not used by any screen yet\n')
        out.append('These files came with the interface icon pack and are kept for later screens: ' + ', '.join(f'`{x}`' for x in INV['unusedIconFiles']) + '.\n')
    with open(os.path.join(ROOT, 'ICON_CATALOG.md'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out))


# ---------------------------------------------------------------------------
# CSV
# ---------------------------------------------------------------------------

FIELDS = ['section', 'asset_id', 'name', 'group', 'pantheon', 'shown_on', 'today', 'today_file', 'priority', 'brief', 'details', 'lore']


def rows_flat():
    for s in INV['sections']:
        for r in s['rows']:
            yield s, r


def build_csv():
    with open(os.path.join(SRC, 'icon_catalog.csv'), 'w', encoding='utf-8', newline='') as f:
        w = csv.writer(f, lineterminator='\n')
        w.writerow(FIELDS)
        for s, r in rows_flat():
            w.writerow([
                s['title'], r['assetId'], r['name'], r.get('group', ''), r.get('pantheon', ''), r['where'],
                CURRENT_LABEL[r['current']['type']], current_file(r['current']) or '', r['priority'], r['brief'], r.get('details', ''), r.get('lore', ''),
            ])


# ---------------------------------------------------------------------------
# XLSX
# ---------------------------------------------------------------------------

HEAD_FILL = PatternFill('solid', fgColor='1F2A44')
NOW_FILL = PatternFill('solid', fgColor='FFF4D6')
HEAD_FONT = Font(bold=True, color='FFFFFF')
WRAP = Alignment(wrap_text=True, vertical='top')
CENTER = Alignment(horizontal='center', vertical='center')


def thumb_for(path, size=40):
    """A small flattened-on-transparent PNG for embedding (cached)."""
    if not path:
        return None
    full = os.path.join(ROOT, path)
    if not os.path.exists(full):
        return None
    os.makedirs(THUMBS, exist_ok=True)
    key = path.replace('/', '__').replace('\\', '__')
    out = os.path.join(THUMBS, f'{size}_{key}.png')
    if not os.path.exists(out) or os.path.getmtime(out) < os.path.getmtime(full):
        im = Image.open(full).convert('RGBA')
        im.thumbnail((size, size), Image.LANCZOS)
        canvas = Image.new('RGBA', (size, size), (0, 0, 0, 0))
        canvas.paste(im, ((size - im.width) // 2, (size - im.height) // 2), im)
        canvas.save(out)
    return out


def build_xlsx():
    wb = Workbook()
    ws = wb.active
    ws.title = 'Read me'
    style = INV['style']
    ws['A1'] = 'Pantheon Realms — icon catalog'
    ws['A1'].font = Font(bold=True, size=16)
    ws['A2'] = f"Generated by npm run icons:catalog from content {INV['contentVersion']} on {date.today().isoformat()}. One sheet per section; the Status column is yours (it is not overwritten when you keep your own copy)."
    ws['A2'].alignment = WRAP
    r = 4
    for k, v in style.items():
        ws.cell(row=r, column=1, value=k.capitalize()).font = Font(bold=True)
        ws.cell(row=r, column=2, value=v).alignment = WRAP
        r += 1
    r += 1
    ws.cell(row=r, column=1, value='Section').font = Font(bold=True)
    ws.cell(row=r, column=2, value='Entries / without art yet / size').font = Font(bold=True)
    for s in INV['sections']:
        r += 1
        n_now = sum(1 for x in s['rows'] if x['priority'] == 'now')
        ws.cell(row=r, column=1, value=s['title'])
        ws.cell(row=r, column=2, value=f"{len(s['rows'])} / {n_now} / {s['size']}")
    ws.column_dimensions['A'].width = 34
    ws.column_dimensions['B'].width = 120

    headers = ['Today', 'Asset ID (deliver as)', 'Name', 'Group', 'Pantheon', 'Shown on', 'Today (what is shown)', 'Priority', 'What to draw', 'Details', 'Lore', 'Status']
    widths = [8, 38, 26, 22, 14, 36, 30, 9, 60, 50, 50, 14]
    for s in INV['sections']:
        sh = wb.create_sheet(s['title'][:31].replace('/', '-'))
        for i, h in enumerate(headers, start=1):
            c = sh.cell(row=1, column=i, value=h)
            c.fill = HEAD_FILL
            c.font = HEAD_FONT
            c.alignment = CENTER
            sh.column_dimensions[get_column_letter(i)].width = widths[i - 1]
        sh.freeze_panes = 'C2'
        dv = DataValidation(type='list', formula1='"To do,In progress,Review,Done"', allow_blank=True)
        sh.add_data_validation(dv)
        for n, row in enumerate(s['rows'], start=2):
            vals = [None, row['assetId'], row['name'], row.get('group', ''), row.get('pantheon', ''), row['where'], current_text(row['current']), row['priority'], row['brief'], row.get('details', ''), row.get('lore', ''), 'To do' if row['priority'] == 'now' else '']
            for i, v in enumerate(vals, start=1):
                c = sh.cell(row=n, column=i, value=v)
                c.alignment = WRAP
                if row['priority'] == 'now' and i > 1:
                    c.fill = NOW_FILL
            dv.add(f'L{n}')
            sh.row_dimensions[n].height = 34
            t = thumb_for(current_file(row['current']))
            if t:
                img = XLImage(t)
                img.width = 40
                img.height = 40
                sh.add_image(img, f'A{n}')
        sh.auto_filter.ref = f'A1:{get_column_letter(len(headers))}{len(s["rows"]) + 1}'
    wb.save(os.path.join(SRC, 'ICON_CATALOG.xlsx'))


if __name__ == '__main__':
    build_markdown()
    build_csv()
    build_xlsx()
    total = sum(len(s['rows']) for s in INV['sections'])
    print(f'icon catalog: {total} entries → ICON_CATALOG.md, assets-source/icons/icon_catalog.csv, assets-source/icons/ICON_CATALOG.xlsx')
    sys.exit(0)
