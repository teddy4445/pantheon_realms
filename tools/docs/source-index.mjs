/** Generate a portable navigation atlas, not API documentation or a parser.
 * Declared exports are a lexical aid; package entry points define supported APIs.
 * --check verifies freshness without modifying the checked-in atlas. */
import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const slash = value => value.replaceAll('\\', '/');
const extensions = /\.(?:ts|tsx|mts|mjs|cjs|js|py|css|ps1|cmd)$/;
const ignored = new Set(['node_modules', 'dist', 'renderer', 'release', '.asset-cache', '__pycache__', 'test-results', 'playwright-report', '.git']);
async function walk(relative) {
  const files = [];
  for (const item of await readdir(path.join(root, relative), { withFileTypes: true })) {
    if (ignored.has(item.name)) continue;
    const name = slash(path.join(relative, item.name));
    if (item.isDirectory()) files.push(...await walk(name));
    else if (extensions.test(item.name)) files.push(name);
  }
  return files.sort();
}
const groups = [];
for (const parent of ['packages', 'apps']) {
  for (const entry of (await readdir(path.join(root, parent), { withFileTypes: true })).sort((a,b)=>a.name.localeCompare(b.name))) {
    if (!entry.isDirectory()) continue;
    const folder = `${parent}/${entry.name}`;
    // Test sources have their own coverage guides; this atlas covers production modules and build configuration.
    const files = (await walk(folder)).filter(file => !/(?:^|\/)(?:test|tests)(?:\/)|\.(?:test|spec)\./.test(file));
    groups.push({ folder, files });
  }
}
groups.push({ folder: 'tools', files: (await walk('tools')).filter(file => !/\.(?:test|spec)\./.test(file)) });
groups.push({ folder: 'Root configuration', files: (await readdir(root)).filter(name => extensions.test(name)).sort() });
const count = groups.reduce((n, g) => n + g.files.length, 0);
let output = `# Source atlas\n\nGenerated by [source-index.mjs](../../tools/docs/source-index.mjs). **${count} source, style, configuration and tooling files** are linked below. Test suites live beside packages and in [tests/e2e](../../tests/e2e).\n\nThis is a navigation index, not a stability guarantee for every exported symbol. The export column lists top-level named declarations found lexically; re-exports and dynamically generated names may not appear. Use each package's README and entry point for supported APIs. Read the [architecture walkthrough](ARCHITECTURE_WALKTHROUGH.md) before changing cross-package behavior.\n\n`;
for (const { folder, files } of groups) {
  output += `## ${folder}\n\n`;
  if (folder.startsWith('packages/') || folder.startsWith('apps/')) output += `[Package guide](../../${folder}/README.md)\n\n`;
  output += '| File | Declared exports / file type |\n| --- | --- |\n';
  for (const file of files) {
    const source = await readFile(path.join(root, file), 'utf8');
    const names = [...source.matchAll(/^export\s+(?:(?:declare|async|abstract)\s+)?(?:function|class|interface|type|enum|const|let)\s+(\w+)/gm)].map(match => match[1]);
    const label = file.startsWith(folder + '/') ? file.slice(folder.length + 1) : file;
    const description = names.length ? [...new Set(names)].map(name => '`' + name + '`').join(', ') : ({'.css':'Stylesheet','.py':'Python tooling','.ps1':'PowerShell tooling','.cmd':'Windows launcher'}[path.extname(file)] ?? 'Module / entry point; follow its imports and re-exports');
    output += `| [${label}](../../${file}) | ${description} |\n`;
  }
  output += '\n';
}
const target = path.join(root, 'docs/development/SOURCE_INDEX.md');
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== output) throw new Error('Source atlas is stale. Run node tools/docs/source-index.mjs.');
  console.log(`Source atlas is current (${count} files).`);
} else {
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, output);
  console.log(`Indexed ${count} files in docs/development/SOURCE_INDEX.md.`);
}
